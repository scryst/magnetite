// Regenerates the poured name — the `#wordmark` symbol in index.html and
// site/wordmark.svg — from
// the distance field in js/wordmark.js, and says how closely that field's M
// matches the icon's.
//
// The finale draws the name live, as a field, on WebGL. Everywhere that cannot
// — the masthead, a browser without WebGL2, forced colours, no scripts — gets
// this: the same field traced at its zero crossing and fitted with cubics by
// gen-mark.mjs's own tracer, so the still and the pour are one shape.
//
// SHAPE in wordmark.js is FITTED, not chosen: the distance field's M is scored
// against the icon's M (the contour gen-mark.mjs traces from the master) by
// intersection over union. `--fit` searches for the best SHAPE and prints it;
// paste it into wordmark.js and run again.
//
// Run: node site/test/gen-wordmark.mjs [--fit]

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { pour, distance, SHAPE } from '../js/wordmark.js';
import { deriveMark, marchingSquares, chain, fitClosed, fitError, pathData, bezierAt } from './gen-mark.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const indexPath = join(here, '..', 'index.html');

/** Field samples per H, the cap height. */
const GRID = 96;
/** Output units per H, so a rounded tenth is a thousandth of the cap height. */
const OUT = 100;
/** How far a fitted curve may stray from the traced contour, in samples. */
const TOLERANCE = 0.3;
/** Worse than this and the field is no longer the icon's liquid. */
const IOU_FLOOR = 0.92;

// ---------------------------------------------------------------- the name

/** The name traced out of its own field: curves in output units, ink box at 0 0. */
export function deriveWordmark(shape = SHAPE) {
  const { pieces, bounds: [x0, y0, x1, y1] } = pour('MAGNETITE', shape);
  const pad = 2;
  const width = Math.ceil((x1 - x0) * GRID) + pad * 2;
  const height = Math.ceil((y1 - y0) * GRID) + pad * 2;
  // Positive in the ink, as the tracer reads it.
  const field = new Float64Array(width * height);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      field[y * width + x] = -distance(x0 + (x - pad) / GRID, y0 + (y - pad) / GRID, pieces, shape.tension);
    }
  }
  const rings = chain(marchingSquares({ field, width, height }).segments);
  let worst = 0;
  const toOut = ([x, y]) => [((x - pad) * OUT) / GRID, ((y - pad) * OUT) / GRID];
  const curves = rings.map((ring) => {
    const fitted = fitClosed(ring, TOLERANCE);
    worst = Math.max(worst, fitError(ring, fitted));
    return fitted.map((c) => c.map(toOut));
  });
  if (worst > TOLERANCE * 2) throw new Error(`the fit strayed ${worst.toFixed(3)} samples from the field`);
  const box = [0, 0, Math.ceil((x1 - x0) * OUT), Math.ceil((y1 - y0) * OUT)];
  return { curves, box, rings: rings.length, worst };
}

/** The symbol, whole — what the generator writes and portcheck can re-derive. */
export function wordmarkSymbol(mark) {
  const d = mark.curves.map((c) => pathData(c, '    ')).join('\n    ');
  return `<symbol id="wordmark" viewBox="${mark.box.join(' ')}">\n`
    + `    <path fill="currentColor" d="${d}"/>\n  </symbol>`;
}

/**
 * The same name as a file, for places that cannot `<use>` the page's symbol:
 * the README, a press kit. Ink on light, paper on dark, from the page's tokens.
 */
export function wordmarkFile(mark) {
  const d = mark.curves.map((c) => pathData(c, '    ')).join('\n    ');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${mark.box.join(' ')}" role="img" aria-label="Magnetite">
  <!-- GENERATED by test/gen-wordmark.mjs from js/wordmark.js. Never edit by hand. -->
  <style>path { fill: #222022 } @media (prefers-color-scheme: dark) { path { fill: #ECEBE6 } }</style>
  <path d="${d}"/>
</svg>
`;
}

/** Matches exactly what `wordmarkSymbol` writes, so the generator can find it again. */
export const SYMBOL_IN_PAGE = /<symbol id="wordmark" viewBox="[^"]*">\s*<path fill="currentColor" d="[^"]*"\/>\s*<\/symbol>/;
/** Every picture of the name borrows the symbol's box, for its own aspect. */
const USE_BOX = /viewBox="[^"]*"( data-wordmark)/g;

// ---------------------------------------------------------------- the fit

/** The icon's M as a mask, and a scorer for any SHAPE's M against it. */
function iconScorer() {
  const { inkCurves } = deriveMark();
  const edges = [];
  for (const c of inkCurves) {
    let prev = c[0];
    for (let s = 1; s <= 12; s++) { const q = bezierAt(c, s / 12); edges.push([prev, q]); prev = q; }
  }
  let X0 = Infinity, Y0 = Infinity, X1 = -Infinity, Y1 = -Infinity;
  for (const [[x, y]] of edges) { X0 = Math.min(X0, x); Y0 = Math.min(Y0, y); X1 = Math.max(X1, x); Y1 = Math.max(Y1, y); }
  const R = 0.5; // mask samples per master pixel
  const gw = Math.round((X1 - X0) * R), gh = Math.round((Y1 - Y0) * R);
  const target = new Uint8Array(gw * gh);
  for (let gy = 0; gy < gh; gy++) {
    const y = Y0 + (gy + 0.5) / R;
    const xs = [];
    for (const [a, b] of edges) {
      if ((a[1] <= y) !== (b[1] <= y)) xs.push(a[0] + ((y - a[1]) / (b[1] - a[1])) * (b[0] - a[0]));
    }
    xs.sort((p, q) => p - q);
    for (let k = 0; k + 1 < xs.length; k += 2) {
      for (let gx = 0; gx < gw; gx++) {
        const x = X0 + (gx + 0.5) / R;
        if (x >= xs[k] && x < xs[k + 1]) target[gy * gw + gx] = 1;
      }
    }
  }
  // Both Ms are set to the same ink width, from the same top-left corner.
  return (shape) => {
    const { pieces } = pour('M', shape);
    let x0 = Infinity, y0 = Infinity, x1 = -Infinity;
    for (let y = -0.4; y <= 1.5; y += 0.01) {
      for (let x = -0.4; x <= 1.9; x += 0.01) {
        if (distance(x, y, pieces, shape.tension) < 0) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); }
      }
    }
    const scale = (x1 + 0.01 - x0) / (gw / R);
    let inter = 0, union = 0;
    for (let gy = 0; gy < gh; gy++) {
      for (let gx = 0; gx < gw; gx++) {
        const a = distance(x0 + ((gx + 0.5) / R) * scale, y0 + ((gy + 0.5) / R) * scale, pieces, shape.tension) < 0 ? 1 : 0;
        const b = target[gy * gw + gx];
        inter += a & b; union += a | b;
      }
    }
    return inter / union;
  };
}

/** Coordinate descent over SHAPE, halving each range every round. */
function fit(score) {
  const ranges = { half: [0.1, 0.16], pool: [0.06, 0.24], span: [0.2, 0.7], lift: [-0.05, 0.2], join: [0, 0.14], tension: [0.01, 0.24] };
  let best = { ...SHAPE }, bestScore = score(best);
  for (let round = 0; round < 6; round++) {
    for (const [key, [lo, hi]] of Object.entries(ranges)) {
      const step = (hi - lo) / 2 ** round / 6;
      for (let s = -3; s <= 3; s++) {
        const candidate = { ...best, [key]: Math.min(hi, Math.max(lo, best[key] + s * step)) };
        const sc = score(candidate);
        if (sc > bestScore) { bestScore = sc; best = candidate; }
      }
    }
  }
  return { best, bestScore };
}

// ---------------------------------------------------------------- run

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const score = iconScorer();
  const iou = score(SHAPE);
  console.log(`M against the icon: IoU ${iou.toFixed(4)}`);
  if (process.argv.includes('--fit')) {
    const { best, bestScore } = fit(score);
    const rounded = Object.fromEntries(Object.entries(best).map(([k, v]) => [k, +v.toFixed(3)]));
    console.log(`best fit: IoU ${bestScore.toFixed(4)} with SHAPE = ${JSON.stringify(rounded)}`);
    process.exit(0);
  }
  if (iou < IOU_FLOOR) throw new Error(`the field's M has drifted from the icon's (IoU ${iou.toFixed(4)} < ${IOU_FLOOR})`);

  const mark = deriveWordmark();
  const count = mark.curves.reduce((n, c) => n + c.length, 0);
  console.log(`name: ${mark.rings} rings, ${count} cubics, worst deviation ${mark.worst.toFixed(3)} samples, `
    + `box ${mark.box.join(' ')}`);
  const index = readFileSync(indexPath, 'utf8');
  if (!SYMBOL_IN_PAGE.test(index)) throw new Error('index.html no longer holds the #wordmark symbol in the expected shape');
  writeFileSync(indexPath, index
    .replace(SYMBOL_IN_PAGE, wordmarkSymbol(mark))
    .replace(USE_BOX, `viewBox="${mark.box.join(' ')}"$1`));
  writeFileSync(join(here, '..', 'wordmark.svg'), wordmarkFile(mark));
  console.log('wrote the #wordmark symbol and every data-wordmark viewBox in site/index.html, '
    + 'and site/wordmark.svg');
}
