// Regenerates site/data/real-levels.js from the app's own Resources/real-levels.txt.
//
// The site claims the ambient motion is real captured audio, so the frames have
// to BE the app's frames rather than a copy somebody pasted once. portcheck.mjs
// re-reads the .txt and asserts the generated module still matches it.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..');

export function parseLevels(text) {
  return text.split('\n')
    .map((line) => line.trim())
    .filter((line) => line.length > 0)
    .map((line) => line.split(/\s+/).map(Number))
    .filter((values) => values.length === 12 && values.every((v) => Number.isFinite(v)));
}

export function loadSourceLevels() {
  return parseLevels(readFileSync(join(repo, 'Resources', 'real-levels.txt'), 'utf8'));
}

/** The lowest-energy frame, which is where the replay loops so the period is not audible. */
export function quietestFrame(frames) {
  let best = 0;
  let bestSum = Infinity;
  frames.forEach((frame, index) => {
    const sum = frame.reduce((a, b) => a + b, 0);
    if (sum < bestSum) { bestSum = sum; best = index; }
  });
  return { index: best, sum: bestSum };
}

/**
 * The largest summed positive band rise, and where it is.
 *
 * The same quantity `theEntranceIsCausedByTheCapture` picks the entrance by.
 * Reported in the header because whether it falls inside the looped span is
 * what decides if the page's one staged gesture is also its ambient one.
 */
function loudestOnset(frames) {
  let best = 0;
  let bestRise = -1;
  for (let i = 1; i < frames.length; i++) {
    let rise = 0;
    for (let b = 0; b < frames[i].length; b++) rise += Math.max(0, frames[i][b] - frames[i - 1][b]);
    if (rise > bestRise) { bestRise = rise; best = i; }
  }
  return { index: best, rise: bestRise };
}

/**
 * The rate the capture was taken at, read out of the app.
 *
 * Not a constant here, because a constant here is what went wrong: the header
 * this file writes said 60Hz for as long as the capture has existed, and the
 * levels arrive at 30 — `AudioLevels.swift` pumps its read loop on a 33ms
 * sleep, and the commit that added the capture (cefd7f7) says so in as many
 * words. Every duration below was therefore half of the truth. Read from the
 * source of the fact and the header cannot drift from it again;
 * `theCaptureIsReplayedAtItsOwnRate` holds site.js to the same number.
 */
function captureHz() {
  const swift = readFileSync(
    join(repo, 'Sources', 'NotchApp', 'Audio', 'AudioLevels.swift'), 'utf8');
  const pump = swift.match(/Task\.sleep\(for:\s*\.milliseconds\((\d+)\)\)/);
  if (!pump) throw new Error('AudioLevels.swift no longer pumps on a milliseconds sleep');
  return Math.round(1000 / Number(pump[1]));
}

function main() {
  const frames = loadSourceLevels();
  const loop = quietestFrame(frames);
  const onset = loudestOnset(frames);
  const period = frames.length - loop.index;
  const hz = captureHz();
  const body = frames.map((f) => `  [${f.map((v) => v.toFixed(2)).join(',')}],`).join('\n');
  const out = `// GENERATED by site/test/gen-levels.mjs from Resources/real-levels.txt.
// Do not edit by hand — portcheck.mjs asserts this still matches the source.
//
// ${frames.length} frames of real captured band levels from the app's own audio
// tap, taken at ${hz}Hz — the rate AudioLevels.swift republishes at, read from
// that file rather than written down here. ${(frames.length / hz).toFixed(3)} seconds of music.
// The replay loops at frame ${loop.index}, the lowest-energy frame in the set
// (sum ${loop.sum.toFixed(2)}), so the SEAM is the quietest moment available and the
// splice itself does not show.
//
// The PERIOD is a separate claim and a header here used to make it: "the period
// is not detectable". It is not the same fact. A quiet seam hides the join; it
// does nothing about the repeat. ${period} frames at ${hz}Hz is ${(period / hz).toFixed(3)}s, and the
// capture's largest onset — frame ${onset.index}, summed positive rise ${onset.rise.toFixed(3)}, at
// ${(onset.index / hz).toFixed(2)}s — sits ${onset.index >= loop.index ? 'INSIDE' : 'outside'} the looped span, so the biggest gesture
// in the capture comes back on that period for as long as the page is open.
// Lengthening it takes more captured audio; a different loop point cannot buy
// it, because the loop can only ever be shorter than the capture.
//
// Both durations here were half this until 2026-08-28. The header said 60Hz,
// site.js indexed at 60Hz, and portprobe dumped at 60Hz — three statements of
// one assumption, none of them a measurement, against an app that has published
// at 30 since before this file existed.
//
// Two places these seconds are approximate, said out loud so the next reader
// does not treat them as measured. 33ms is 30.30Hz and a sleep is a FLOOR, so
// the real rate is at most that and the durations are lower bounds — ${(frames.length / (1000 / 33)).toFixed(2)}s rather
// than ${(frames.length / hz).toFixed(3)}s at the nominal rate, a difference of about 1%. And tick()
// logs only frames it judges live, so a quiet passage is DROPPED rather than
// written: 240 logged frames are 240 sounding frames, and they are contiguous
// only if nothing fell out mid-capture. Nothing here needs them to be — the
// replay treats them as consecutive because the app's own physics did — but a
// gap would make the wall-clock span longer than the arithmetic above.

export const LOOP_FRAME = ${loop.index};
export const REAL_LEVELS = [
${body}
];
`;
  writeFileSync(join(repo, 'site', 'data', 'real-levels.js'), out);
  process.stdout.write(`wrote ${frames.length} frames, loop at ${loop.index} (sum ${loop.sum.toFixed(2)})\n`);
}

if (process.argv[1] && process.argv[1].endsWith('gen-levels.mjs')) main();
